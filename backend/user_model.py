from pydantic import BaseModel, EmailStr, Field

class UserCreate(BaseModel):
    email: EmailStr
    password: str

class UserLogin(BaseModel):
    message: str
    auth_token: str # The token generated by the server
    email: EmailStr # The email of the logged-in user

class AnswerRequest(BaseModel):
    session_id: str
    answer: str
    
class SubscriptionRequest(BaseModel):
    subscribe: bool

class FCMTokenRequest(BaseModel):
    fcm_token: str = Field(..., min_length=10) # Basic validation
